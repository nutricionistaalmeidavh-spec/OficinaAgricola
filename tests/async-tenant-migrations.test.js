test('native D1 tenant schema migrates canonical operational, financial, stock and fiscal tables atomically',async()=>{
 const db=openDatabase(':memory:');
 try{
  const binding={
   prepare(sql){return {
     bind(...values){return {
       async first(){return db.prepare(sql).get(...values);},
       async all(){return {results:db.prepare(sql).all(...values)};},
       async run(){const result=db.prepare(sql).run(...values);return {meta:{changes:Number(result.changes),last_row_id:Number(result.lastInsertRowid)}};}
     }}
   }},
   async batch(stmts){const res=[];db.exec('BEGIN IMMEDIATE');try{for(const stmt of stmts)res.push(await stmt.run());db.exec('COMMIT');return res;}catch(e){db.exec('ROLLBACK');throw e;}}
  };
  const port=createD1Port({binding});
  await migrateAsyncTenantStore(port);
  await migrateAsyncTenantStore(port);
  for(const name of [
   'customers','machines','work_orders','work_order_status_history','quotes','quote_items',
   'parts','inventory_movements','work_order_parts','receipts','payment_events',
   'expenses','attachments','fiscal_documents','fiscal_events','fiscal_homologation_evidence'
  ])assert.ok(db.prepare("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?").get(name),name);
  const all=await port.all('SELECT version FROM async_schema_migrations');
  assert.equal(all.length,1);
  assert.equal(await port.first('SELECT COUNT(*) n FROM work_orders').then(r=>r.n),0);
 }finally{db.close();}
});
test('PostgreSQL tenant schema uses identity columns and no SQLite-only syntax',()=>{
 const sql=asyncTenantSchema('postgres');
 assert.ok(sql.some(s=>s.includes('GENERATED BY DEFAULT AS IDENTITY')));
 assert.ok(sql.some(s=>s.includes('DOUBLE PRECISION')),'SQLite REAL must retain 64-bit precision in PostgreSQL');
 assert.ok(sql.every(s=>!(/\b[a-z_][a-z0-9_]*\s+REAL\b/i.test(s))),'PostgreSQL REAL column type would silently round SQLite quantities');
 assert.ok(sql.some(s=>s.includes('customer_id BIGINT NOT NULL REFERENCES customers(id)')),'foreign keys must support 48-bit ids');
 assert.ok(sql.some(s=>s.includes('source_id BIGINT NOT NULL')),'payment events reference large entity IDs');
 assert.ok(sql.every(s=>!s.includes('AUTOINCREMENT')&&!s.includes('sqlite_master')));
 assert.ok(sql.some(s=>s.includes('CREATE TABLE IF NOT EXISTS fiscal_documents')));
 assert.ok(sql.some(s=>s.includes('CREATE TABLE IF NOT EXISTS tenant_remote_upload_requests')),
   'native S3 upload idempotency table must exist before any attachment operation');
 assert.ok(sql.some(s=>s.includes('CREATE SEQUENCE IF NOT EXISTS async_os_number_seq')),'PG must allocate order number without MAX race');
 assert.ok(sql.some(s=>s.includes('os_number BIGINT NOT NULL UNIQUE')),'sequence uses BIGINT OS numbers');
});

test('PostgreSQL native schema uses BIGINT for generated 48-bit IDs, foreign keys and monetary cents',()=>{
 const statements=asyncTenantSchema('postgres').join('\n');
 for(const field of ['customer_id','machine_id','work_order_id','part_id','source_id','origin_id','created_by','amount_cents','total_cents','quote_total_cents']){
   assert.match(statements,new RegExp('\\b'+field+'\\s+BIGINT\\b'),
     'PostgreSQL column '+field+' must not silently narrow 48-bit identifiers or money');
 }
 assert.match(statements,/BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
});

test('tenant database identity rejects reuse by another company or branch',async()=>{
 const db=openDatabase(':memory:');
 try{
  const port=createD1Port({binding:{
   prepare(sql){return{bind(...args){return{
    async first(){return db.prepare(sql).get(...args);},
    async all(){return{results:db.prepare(sql).all(...args)};},
    async run(){const r=db.prepare(sql).run(...args);return{meta:{changes:r.changes}};}
   }}}},
   async batch(commands){db.exec('BEGIN IMMEDIATE');try{const result=[];
    for(const q of commands)result.push(await q.run());
    db.exec('COMMIT');return result;
   }catch(e){db.exec('ROLLBACK');throw e;}}
  }});
  await migrateAsyncTenantStore(port);
  const first=await claimAsyncTenantIdentity(port,{companyId:2,unitId:4});
  assert.equal(first.companyId,2);
  assert.equal(first.unitId,4);
  assert.deepEqual(await claimAsyncTenantIdentity(port,{companyId:2,unitId:4}),first);
  await assert.rejects(claimAsyncTenantIdentity(port,{companyId:3,unitId:4}),/outro tenant/);
  await assert.rejects(claimAsyncTenantIdentity(port,{companyId:2,unitId:5}),/outro tenant/);
 }finally{db.close();}
});

test('D1 native schema covers every canonical SQLite business table and column',async()=>{
 const old=openDatabase(':memory:'),native=openDatabase(':memory:');
 try{
  migrate(old);migrateAssistencia(old);
  const binding={
   prepare(sql){return{bind(...args){return{
    async first(){return native.prepare(sql).get(...args);},
    async all(){return {results:native.prepare(sql).all(...args)};},
    async run(){const r=native.prepare(sql).run(...args);return{meta:{changes:r.changes}};}
   }}}},
   async batch(stmts){native.exec('BEGIN IMMEDIATE');try{const results=[];
    for(const s of stmts)results.push(await s.run());
    native.exec('COMMIT');return results;
   }catch(e){native.exec('ROLLBACK');throw e;}}
  };
  const port=createD1Port({binding});await migrateAsyncTenantStore(port);
  const tables=db=>db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").all().map(x=>x.name);
  const missing=tables(old).filter(name=>!tables(native).includes(name));
  assert.deepEqual(missing,[],'entire SQLite canonical table surface must exist in D1');
  for(const table of tables(old)){
   const names=db=>new Set(db.prepare('PRAGMA table_info("'+table+'")').all().map(c=>c.name));
   const extra=[...names(old)].filter(column=>!names(native).has(column));
   assert.deepEqual(extra,[],table+' has missing domain columns in D1');
  }
  const indexes=db=>db.prepare("SELECT name FROM sqlite_master WHERE type='index' AND name NOT LIKE 'sqlite_%'").all().map(x=>x.name);
  const missingIndexes=indexes(old).filter(name=>!indexes(native).includes(name));
  assert.deepEqual(missingIndexes,[],'D1 must preserve all legacy index names for pagination, filters and uniqueness');
 }finally{old.close();native.close();}
});

import {createHash,timingSafeEqual} from 'node:crypto';
import {asyncTenantSchema,claimAsyncTenantIdentity} from './async-tenant-migrations.js';
import {buildCanonicalSqliteManifest,verifyCanonicalTargetManifest} from './tenant-migration-manifest.js';
import {readRemoteAttachment} from './remote-attachments.js';

// Explicit OFFLINE migration, intended only for a NEW/empty PostgreSQL or
// Cloudflare D1 staging database. Existing local SQLite is read-only.
// The target cannot serve requests until checksums match and tenant identity
// has been claimed. There is NO automatic customer database switch.
const quote=value=>{
 if(typeof value!=='string'||!/^[A-Za-z][A-Za-z0-9_]*$/.test(value))
   throw Error('Identificador SQL não canônico');
 return '"'+value+'"';
};
const fail=message=>{throw Error(message);};
function sortByForeignKey(sourceDb,names){
 const known=new Set(names),done=new Set(),visiting=new Set(),out=[];
 function visit(table){
   if(done.has(table))return;
   if(visiting.has(table))fail('Ciclo de chaves estrangeiras; requer importação especializada: '+table);
   visiting.add(table);
   const dependencies=sourceDb.prepare('PRAGMA foreign_key_list('+quote(table)+')').all()
     .map(x=>x.table).filter(x=>x!==table&&known.has(x));
   for(const parent of [...new Set(dependencies)].sort())visit(parent);
   visiting.delete(table);done.add(table);out.push(table);
 }
 for(const name of [...names].sort())visit(name);
 return out;
}
function sqliteRows(db,table,entry){
 const cols=entry.columns.map(quote).join(', '),
   order=entry.keys.map(quote).join(', ');
 return db.prepare('SELECT '+cols+' FROM '+quote(table)+' ORDER BY '+order).iterate();
}
function readySqlite(sourceDb){
 if(!sourceDb||typeof sourceDb.prepare!=='function')fail('Origem SQLite aberta e explícita é obrigatória');
 const manifest=buildCanonicalSqliteManifest(sourceDb);
 if(!manifest.readyForRemote)
   fail('Migração bloqueada: '+manifest.unresolvedDiskAttachments+
     ' anexo(s) ainda no disco local precisam ser enviados/verificados antes de trocar o banco');
 return manifest;
}
async function verifyOriginalObjects(sourceDb,objectStore,targetObjectStore){
 const rows=sourceDb.prepare('SELECT * FROM attachments ORDER BY id').iterate();
 for(const row of rows){
   if(!objectStore?.getObject)
     fail('Anexos remotos exigem objectStore R2/MinIO de origem para verificar bytes');
   if(!targetObjectStore?.getObject)
     fail('Anexos remotos exigem storage de destino explícito e já preenchido');
   // The destination prefix/bucket may differ from the original installation.
   // Do not enable a new database until both copies of every blob match.
   const original=await readRemoteAttachment(row,objectStore);
   const target=await readRemoteAttachment(row,targetObjectStore);
   const a=createHash('sha256').update(original).digest();
   const b=createHash('sha256').update(target).digest();
   if(!timingSafeEqual(a,b))
     fail('Integridade divergente no storage de destino para o anexo #'+row.id);
 }
}
async function requirePristineTarget(port,manifest){
 const identity=await port.first('SELECT * FROM async_tenant_identity WHERE id=1');
 if(identity)fail('Banco destino já inicializado para uma empresa/unidade; não sobrescrever');
 const expectedTables=asyncTenantSchema('d1')
   .map(sql=>/^CREATE TABLE IF NOT EXISTS\s+([A-Za-z_][A-Za-z0-9_]*)/.exec(sql)?.[1])
   .filter(table=>table&&!['async_schema_migrations','async_tenant_identity'].includes(table));
 for(const table of expectedTables){
   const row=await port.first('SELECT COUNT(*) n FROM '+quote(table));
   if(Number(row.n)!==0)fail('Banco destino não está vazio: '+table+
     '. Use um novo banco de staging migrado com seed=false.');
 }
}
async function reseedPgSequences(port,manifest){
 const nativeSql=asyncTenantSchema('postgres');
 const identityTables=nativeSql
   .map(sql=>/^CREATE TABLE IF NOT EXISTS\s+([A-Za-z_][A-Za-z0-9_]*)\s*\([\s\S]*?id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/.exec(sql)?.[1])
   .filter(name=>name&&manifest.tables[name]?.columns.includes('id'));
 for(const table of identityTables){
   const identifier=quote(table);
   await port.run(`SELECT setval(pg_get_serial_sequence('${identifier}','id'),
     COALESCE((SELECT MAX(id) FROM ${identifier}),1),
     (SELECT COUNT(*)>0 FROM ${identifier}))`);
 }
 await port.run(`SELECT setval('async_os_number_seq',
   COALESCE((SELECT MAX(os_number) FROM work_orders),1),
   (SELECT COUNT(*)>0 FROM work_orders))`);
 await port.run(`SELECT setval('async_sale_number_seq',
   COALESCE((SELECT MAX(sale_number) FROM sales),1),
   (SELECT COUNT(*)>0 FROM sales))`);
}
/**
 * Must be invoked only with source stopped for writes and a new staging DB
 * initialized via migrateAsyncTenantStore(port,{seed:false}).
 *
 * D1 cannot hold a transaction across arbitrarily large imports: batches
 * commit in chunks. If interrupted, discard the staging DB and retry. The
 * identity lock remains unset so the normal Worker denies all operations.
 */
export async function importCanonicalSqliteTenant({sourceDb,targetPort,
 companyId,unitId,batchSize=40,objectStore=null,targetObjectStore=null}={}){
 if(!['d1','postgres'].includes(targetPort?.engine))
   fail('Importação exige destino nativo PostgreSQL ou D1, nunca o SQLite local');
 const company=Number(companyId),unit=Number(unitId);
 if(!Number.isSafeInteger(company)||company<1||!Number.isSafeInteger(unit)||unit<1)
   fail('Empresa e unidade obrigatórias para importação auditável');
 const size=Number(batchSize);
 if(!Number.isSafeInteger(size)||size<1||size>100)
   fail('Lote de importação deve conter entre 1 e 100 linhas');
 const manifest=readySqlite(sourceDb);
 await verifyOriginalObjects(sourceDb,objectStore,targetObjectStore);
 await requirePristineTarget(targetPort,manifest);
 const order=sortByForeignKey(sourceDb,Object.keys(manifest.tables));
 let importedRows=0;
 const collect=async(handler)=>{
   for(const table of order){
     const columns=manifest.tables[table].columns;
     const statement='INSERT INTO '+quote(table)+
       '('+columns.map(quote).join(',')+') VALUES('+
       columns.map(()=>'?').join(',')+')';
     let page=[];
     for(const row of sqliteRows(sourceDb,table,manifest.tables[table])){
       page.push({sql:statement,params:columns.map(name=>row[name]??null)});
       importedRows++;
       if(page.length>=size){await handler(page);page=[];}
     }
     if(page.length)await handler(page);
   }
 };
 if(targetPort.engine==='d1'){
   await collect(queries=>targetPort.batch(queries));
 }else{
   await targetPort.transaction(async tx=>{
     await collect(async queries=>{
       for(const query of queries)await tx.run(query.sql,query.params);
     });
   });
 }
 const after=buildCanonicalSqliteManifest(sourceDb);
 if(after.digest!==manifest.digest)
   fail('SQLite de origem mudou durante importação. Não ativar o banco destino; repita com a oficina parada');
 const verification=await verifyCanonicalTargetManifest(targetPort,manifest);
 if(!verification.ok)
   fail('Destino divergiu do SQLite original; não associar tenant: '+
     verification.differences.map(x=>x.table).join(', '));
 if(targetPort.engine==='postgres')await reseedPgSequences(targetPort,manifest);
 const identity=await claimAsyncTenantIdentity(targetPort,{companyId:company,unitId:unit});
 return {verified:true,sourceDigest:manifest.digest,sourceRows:manifest.rowsTotal,
   importedRows,importedTables:order.length,identity,targetEngine:targetPort.engine,
   readyForCutover:true};
}

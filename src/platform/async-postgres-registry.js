import {createHash,randomBytes,scrypt,scryptSync,timingSafeEqual} from 'node:crypto';

// Global registry: one explicitly provisioned PostgreSQL database for users,
// sessions, companies and memberships. No SQLite fallback or D1 emulation.
const ROLES=new Set(['ADMIN','ATENDIMENTO','TECNICO','FINANCEIRO']);
const SLUG=/^[a-z][a-z0-9-]{1,39}$/;
const CODE=/^[A-Z0-9_-]{2,32}$/;
const now=()=>new Date().toISOString();
const fail=(message,status=403)=>{throw Object.assign(new Error(message),{status});};
const id=value=>{
 const n=Number(value);
 if(!Number.isSafeInteger(n)||n<1)fail('Identificador inválido',400);
 return n;
};
const username=value=>{
 const s=String(value??'').trim().toLowerCase();
 if(!/^[a-z0-9_.-]{3,40}$/.test(s))fail('Usuário inválido',400);
 return s;
};
const role=value=>{
 if(!ROLES.has(value))fail('Perfil inválido',400);
 return value;
};
const digest=token=>createHash('sha256').update(token).digest('hex');
const cleanName=value=>{
 const s=String(value??'').trim();
 if(s.length<2||s.length>120)fail('Nome inválido',400);
 return s;
};
function passwordHash(password){
 if(typeof password!=='string'||password.length<12||password.length>256)
   fail('Senha deve ter entre 12 e 256 caracteres',400);
 const salt=randomBytes(16);
 return 'scrypt$'+salt.toString('hex')+'$'+scryptSync(password,salt,64).toString('hex');
}
async function passwordMatches(password,encoded){
 const [kind,saltHex,hashHex]=String(encoded??'').split('$');
 if(kind!=='scrypt'||!/^[a-f0-9]{32}$/i.test(saltHex??'')||!/^[a-f0-9]{128}$/i.test(hashHex??''))
   return false;
 try{
   const expected=Buffer.from(hashHex,'hex');
   const actual=await new Promise((resolve,reject)=>
     scrypt(String(password??''),Buffer.from(saltHex,'hex'),64,
       (error,result)=>error?reject(error):resolve(result)));
   return timingSafeEqual(expected,actual);
 }catch{return false;}
}
const DUMMY_PASSWORD_HASH='scrypt$59a16c0f49265c11604b4b2782f6c32d$'+
 '110df40dbe83db0b7ab6f73ed3b825a726cc26f9147d09a83dbbecf725bf3c02'+
 '737747c94e4810a58613104ecfe4e882865311b4e4513d7598ab1ab4434043a86';
const safeUser=row=>({
 id:id(row.id),username:row.username,name:row.name,role:row.role
});
const DDL=[
 "CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username TEXT NOT NULL,name TEXT NOT NULL,password_hash TEXT NOT NULL,role TEXT NOT NULL CHECK (role IN ('ADMIN','ATENDIMENTO','TECNICO','FINANCEIRO')),active INTEGER NOT NULL DEFAULT 1 CHECK(active IN(0,1)),created_at TEXT NOT NULL,updated_at TEXT NOT NULL)",
 "CREATE UNIQUE INDEX IF NOT EXISTS idx_registry_user_handle ON users(lower(username))",
 "CREATE TABLE IF NOT EXISTS sessions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,token_hash TEXT NOT NULL UNIQUE,user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,created_at TEXT NOT NULL,expires_at TEXT NOT NULL)",
 "CREATE INDEX IF NOT EXISTS idx_registry_sessions_user ON sessions(user_id,expires_at)",
 "CREATE TABLE IF NOT EXISTS tenant_companies (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,slug TEXT NOT NULL UNIQUE,name TEXT NOT NULL,active INTEGER NOT NULL DEFAULT 1 CHECK(active IN(0,1)),created_at TEXT NOT NULL)",
 "CREATE TABLE IF NOT EXISTS tenant_units (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,company_id BIGINT NOT NULL REFERENCES tenant_companies(id),code TEXT NOT NULL,name TEXT NOT NULL,active INTEGER NOT NULL DEFAULT 1 CHECK(active IN(0,1)),created_at TEXT NOT NULL,UNIQUE(company_id,code))",
 "CREATE TABLE IF NOT EXISTS tenant_memberships (user_id BIGINT NOT NULL REFERENCES users(id),unit_id BIGINT NOT NULL REFERENCES tenant_units(id),role TEXT NOT NULL CHECK (role IN ('ADMIN','ATENDIMENTO','TECNICO','FINANCEIRO')),active INTEGER NOT NULL DEFAULT 1 CHECK(active IN(0,1)),PRIMARY KEY(user_id,unit_id))",
 "CREATE TABLE IF NOT EXISTS tenant_platform_admins (user_id BIGINT PRIMARY KEY REFERENCES users(id))",
 "CREATE TABLE IF NOT EXISTS tenant_audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_user_id BIGINT NOT NULL REFERENCES users(id),action TEXT NOT NULL,company_id BIGINT NOT NULL REFERENCES tenant_companies(id),unit_id BIGINT REFERENCES tenant_units(id),target_user_id BIGINT REFERENCES users(id),detail_json TEXT NOT NULL,created_at TEXT NOT NULL)",
 "CREATE INDEX IF NOT EXISTS idx_registry_audit_company ON tenant_audit(company_id,id DESC)",
 "CREATE INDEX IF NOT EXISTS idx_registry_memberships_unit ON tenant_memberships(unit_id,active,user_id)",
 "CREATE INDEX IF NOT EXISTS idx_registry_units_company ON tenant_units(company_id,active)"
];
// Reviewed PostgreSQL registry DDL; applied transactionally.
const ddl=DDL;
const validCompanyId=value=>id(value);
async function member(p,userId,unitId){
 const unit=await p.first(
  'SELECT u.id,u.company_id AS "companyId",u.code,u.name,m.role FROM tenant_memberships m JOIN tenant_units u ON u.id=m.unit_id JOIN tenant_companies c ON c.id=u.company_id JOIN users x ON x.id=m.user_id WHERE m.user_id=? AND u.id=? AND m.active=1 AND u.active=1 AND c.active=1 AND x.active=1',
  [id(userId),id(unitId)]);
 if(!unit)fail('Permissão: acesso à unidade negado');
 return unit;
}
async function companyAdmin(p,userId,companyId){
 const found=await p.first(
  'SELECT 1 AS ok FROM tenant_memberships m JOIN tenant_units u ON u.id=m.unit_id JOIN tenant_companies c ON c.id=u.company_id JOIN users x ON x.id=m.user_id WHERE m.user_id=? AND u.company_id=? AND m.active=1 AND m.role=? AND u.active=1 AND c.active=1 AND x.active=1 LIMIT 1',
  [id(userId),id(companyId),'ADMIN']);
 if(!found)fail('Permissão: administração da empresa necessária');
}
async function reportingAdmin(p,userId,companyId){
 await companyAdmin(p,userId,companyId);
 const excluded=await p.first(
  'SELECT COUNT(*) AS n FROM tenant_units u JOIN tenant_companies c ON c.id=u.company_id LEFT JOIN tenant_memberships m ON m.unit_id=u.id AND m.user_id=? WHERE u.company_id=? AND u.active=1 AND c.active=1 AND (m.user_id IS NULL OR m.active<>1 OR m.role<>?)',
  [id(userId),id(companyId),'ADMIN']);
 if(Number(excluded.n)>0)
  fail('Permissão: relatório global exige acesso administrativo a todas as unidades');
 return true;
}
async function audit(p,actor,action,company,unit,target,detail={}){
 await p.run(
  'INSERT INTO tenant_audit(actor_user_id,action,company_id,unit_id,target_user_id,detail_json,created_at) VALUES(?,?,?,?,?,?,?)',
  [id(actor),action,id(company),unit==null?null:id(unit),target==null?null:id(target),JSON.stringify(detail),now()]);
}
async function platformAdmin(p,userId){
 const found=await p.first('SELECT 1 AS ok FROM tenant_platform_admins p JOIN users u ON u.id=p.user_id WHERE p.user_id=? AND u.active=1',[id(userId)]);
 if(!found)fail('Permissão: administração da plataforma necessária');
}
export function createPostgresTenantRegistry(port){
 if(port?.engine!=='postgres'||!['first','all','run','transaction'].every(k=>typeof port[k]==='function'))
   throw Error('Registry PostgreSQL exige contrato SQL assíncrono transacional real');
 // In-process throttling protects the basic local gateway; production edge
 // should additionally apply global rate limits if horizontally scaled.
 const attempts=new Map();
 function throttle(address){
   const key=String(address||'unknown').slice(0,120),n=Date.now();
   const current=attempts.get(key);
   if(current&&current.until>n&&current.count>=6)fail('Muitas tentativas de acesso. Aguarde 15 minutos.',429);
   if(current&&current.until<=n)attempts.delete(key);
   return key;
 }
 async function initialize({allowBootstrap=false}={}){
   if(typeof allowBootstrap!=='boolean')fail('Bootstrap inválido',400);
   return port.transaction(async tx=>{
     for(const sql of ddl)await tx.run(sql);
     const c=await tx.first('SELECT COUNT(*) AS n FROM tenant_companies');
     const u=await tx.first('SELECT COUNT(*) AS n FROM users');
     if(Number(c.n)===0){
       // An empty registry must never be silently recreated after data loss.
       if(!allowBootstrap||Number(u.n)!==0)
         fail('Registry vazio: bootstrap explícito ou restauração auditada obrigatória',409);
       await tx.run("INSERT INTO tenant_companies(id,slug,name,created_at) VALUES(1,'principal','Oficina principal',?)",[now()]);
       await tx.run("INSERT INTO tenant_units(id,company_id,code,name,created_at) VALUES(1,1,'MATRIZ','Matriz',?)",[now()]);
       await tx.run("SELECT setval(pg_get_serial_sequence('tenant_companies','id'),1,true)");
       await tx.run("SELECT setval(pg_get_serial_sequence('tenant_units','id'),1,true)");
     }
     if(Number(c.n)>0&&Number(u.n)===0&&!allowBootstrap)
       fail('Registry existente sem usuários: restauração auditada obrigatória',409);
     return {engine:'postgres',ready:true,needsAdmin:Number(u.n)===0};
   });
 }
 async function bootstrapAdmin({username:handle,name,password}={}){
   const account=username(handle),fullName=cleanName(name),encoded=passwordHash(password);
   return port.transaction(async tx=>{
     await tx.run('SELECT pg_advisory_xact_lock(812315654)');
     const check=await tx.first('SELECT COUNT(*) AS n FROM users');
     const base=await tx.first('SELECT 1 AS ok FROM tenant_units WHERE id=1 AND company_id=1');
     if(!base)fail('Registry não inicializado',409);
     if(Number(check.n)>0)fail('Administrador inicial já definido; bootstrap desabilitado',409);
     const created=await tx.first(
       "INSERT INTO users(username,name,password_hash,role,created_at,updated_at) VALUES(?,?,?,'ADMIN',?,?) RETURNING id,username,name,role",
       [account,fullName,encoded,now(),now()]);
     const userId=id(created.id);
     await tx.run('INSERT INTO tenant_platform_admins(user_id) VALUES(?)',[userId]);
     await tx.run("INSERT INTO tenant_memberships(user_id,unit_id,role) VALUES(? ,1,'ADMIN')",[userId]);
     await audit(tx,userId,'INITIAL_ADMIN_CREATED',1,1,userId);
     return safeUser(created);
   });
 }
 async function login({username:handle,password,remoteAddress='unknown'}={}){
   const address=throttle(remoteAddress);
   const handleValue=String(handle??'').trim().toLowerCase();
   const user=await port.first('SELECT * FROM users WHERE lower(username)=? AND active=1',[handleValue]);
   const matched=await passwordMatches(password,user?.password_hash||DUMMY_PASSWORD_HASH);
   if(!user||!matched){
     const v=attempts.get(address),t=Date.now();
     attempts.set(address,{count:(v&&v.until>t?v.count:0)+1,until:t+15*60*1000});
     fail('Credenciais inválidas',401);
   }
   attempts.delete(address);
   const token=randomBytes(32).toString('base64url');
   const createdAt=now(),expiresAt=new Date(Date.now()+12*60*60*1000).toISOString();
   await port.run('INSERT INTO sessions(token_hash,user_id,created_at,expires_at) VALUES(?,?,?,?)',
     [digest(token),id(user.id),createdAt,expiresAt]);
   return {token,expiresAt,user:safeUser(user)};
 }
 async function validateSession(token){
   if(typeof token!=='string'||token.length<32)fail('Sessão inválida',401);
   const row=await port.first(
    'SELECT u.id,u.username,u.name,u.role,u.active,s.expires_at FROM sessions s JOIN users u ON u.id=s.user_id WHERE s.token_hash=?',
    [digest(token)]);
   if(!row||!Number(row.active)||Date.parse(row.expires_at)<=Date.now()||
      !Number.isFinite(Date.parse(row.expires_at)))fail('Sessão inválida',401);
   return safeUser(row);
 }
 async function logout(token){
   if(typeof token==='string'&&token.length>=32)
     await port.run('DELETE FROM sessions WHERE token_hash=?',[digest(token)]);
   return {ok:true};
 }
 async function setupRequired(){
   const row=await port.first('SELECT COUNT(*) AS n FROM users');
   return Number(row.n)===0;
 }
 async function isPlatformAdmin(userId){
   const row=await port.first('SELECT 1 AS ok FROM tenant_platform_admins p JOIN users u ON u.id=p.user_id WHERE p.user_id=? AND u.active=1',[id(userId)]);
   return Boolean(row);
 }
 async function listUserUnits(userId){
   return port.all(
    'SELECT u.id,u.company_id AS "companyId",u.code,u.name,u.active AS "unitActive",c.slug AS "companySlug",c.name AS "companyName",c.active AS "companyActive",m.role FROM tenant_memberships m JOIN tenant_units u ON u.id=m.unit_id JOIN tenant_companies c ON c.id=u.company_id JOIN users x ON x.id=m.user_id WHERE m.user_id=? AND x.active=1 AND m.active=1 AND u.active=1 AND c.active=1 ORDER BY c.id,u.id',
    [id(userId)]);
 }
 async function requireCompanyReportingAdmin(userId,companyId){
   return reportingAdmin(port,userId,companyId);
 }
 async function createCompany(actorId,{slug,name}={}){
   const owner=id(actorId),handle=String(slug??'').trim().toLowerCase(),title=cleanName(name);
   if(!SLUG.test(handle))fail('Dados da empresa inválidos',400);
   return port.transaction(async tx=>{
     await platformAdmin(tx,owner);
     const company=await tx.first(
      'INSERT INTO tenant_companies(slug,name,created_at) VALUES(?,?,?) RETURNING id',
      [handle,title,now()]);
     const companyId=id(company.id);
     const unit=await tx.first(
      "INSERT INTO tenant_units(company_id,code,name,created_at) VALUES(?,'MATRIZ','Matriz',?) RETURNING id",
      [companyId,now()]);
     const unitId=id(unit.id);
     await tx.run("INSERT INTO tenant_memberships(user_id,unit_id,role) VALUES(?,?,'ADMIN')",[owner,unitId]);
     await audit(tx,owner,'COMPANY_CREATED',companyId,unitId,owner,{slug:handle});
     return {id:companyId,slug:handle,name:title,unitId};
   });
 }
 async function createUnit(actorId,{companyId,code,name}={}){
   const owner=id(actorId),company=validCompanyId(companyId);
   const normalized=String(code??'').trim().toUpperCase(),title=cleanName(name);
   if(!CODE.test(normalized))fail('Dados da unidade inválidos',400);
   return port.transaction(async tx=>{
     await companyAdmin(tx,owner,company);
     const unit=await tx.first(
      'INSERT INTO tenant_units(company_id,code,name,created_at) VALUES(?,?,?,?) RETURNING id',
      [company,normalized,title,now()]);
     const unitId=id(unit.id);
     await tx.run("INSERT INTO tenant_memberships(user_id,unit_id,role) VALUES(?,?,'ADMIN')",[owner,unitId]);
     await audit(tx,owner,'UNIT_CREATED',company,unitId,owner,{code:normalized});
     return {id:unitId,companyId:company,code:normalized,name:title};
   });
 }
 async function listUnitMembers(actorId,unitId){
   const unit=await member(port,actorId,unitId);
   if(unit.role!=='ADMIN')fail('Permissão: administração da unidade necessária');
   return port.all(
    'SELECT x.id,x.username,x.name,x.active,m.role,m.active AS "membershipActive" FROM tenant_memberships m JOIN users x ON x.id=m.user_id WHERE m.unit_id=? ORDER BY x.name',[unit.id]);
 }
 async function grantMembership(actorId,{unitId,username:handle,name,password,role:access}={}){
   const actor=id(actorId),unitNumber=id(unitId),assignedRole=role(access),account=username(handle);
   return port.transaction(async tx=>{
     const unit=await member(tx,actor,unitNumber);
     if(unit.role!=='ADMIN')fail('Permissão: administração da unidade necessária');
     let target=await tx.first('SELECT id FROM users WHERE lower(username)=?',[account]);
     if(!target){
       const fullName=cleanName(name),encoded=passwordHash(password);
       target=await tx.first(
        "INSERT INTO users(username,name,password_hash,role,created_at,updated_at) VALUES(?,?,?,'ATENDIMENTO',?,?) RETURNING id",
        [account,fullName,encoded,now(),now()]);
     }
     const userId=id(target.id);
     await tx.run(
      'INSERT INTO tenant_memberships(user_id,unit_id,role,active) VALUES(?,?,?,1) ON CONFLICT(user_id,unit_id) DO UPDATE SET role=excluded.role,active=1',
      [userId,unit.id,assignedRole]);
     await audit(tx,actor,'MEMBERSHIP_GRANTED',unit.companyId,unit.id,userId,{role:assignedRole});
     return {id:userId,unitId:unit.id,role:assignedRole};
   });
 }
 async function changeMembership(actorId,{unitId,userId,role:access,active=true}={}){
   const actor=id(actorId),uid=id(unitId),target=id(userId),assignedRole=role(access);
   if(typeof active!=='boolean')fail('Estado inválido',400);
   return port.transaction(async tx=>{
     // Serialize admin changes on the unit row to prevent losing the last admin.
     await tx.first('SELECT id FROM tenant_units WHERE id=? FOR UPDATE',[uid]);
     const unit=await member(tx,actor,uid);
     if(unit.role!=='ADMIN')fail('Permissão: administração da unidade necessária');
     const current=await tx.first('SELECT role,active FROM tenant_memberships WHERE user_id=? AND unit_id=?',[target,uid]);
     if(!current)fail('Vínculo não encontrado',404);
     if(current.role==='ADMIN'&&Number(current.active)===1&&(!active||assignedRole!=='ADMIN')){
       const count=await tx.first("SELECT COUNT(*) AS n FROM tenant_memberships WHERE unit_id=? AND role='ADMIN' AND active=1",[uid]);
       if(Number(count.n)<2)fail('Último administrador da unidade não pode ser removido',409);
     }
     await tx.run('UPDATE tenant_memberships SET role=?,active=? WHERE user_id=? AND unit_id=?',
       [assignedRole,active?1:0,target,uid]);
     await audit(tx,actor,'MEMBERSHIP_CHANGED',unit.companyId,uid,target,{role:assignedRole,active});
     return {id:target,unitId:uid,role:assignedRole,active};
   });
 }
 async function listAudit(actorId,companyId,{limit=100}={}){
   await reportingAdmin(port,actorId,companyId);
   const capped=Math.min(200,Math.max(1,Number(limit)||100));
   return port.all(
    'SELECT id,actor_user_id,action,company_id,unit_id,target_user_id,detail_json,created_at FROM tenant_audit WHERE company_id=? ORDER BY id DESC LIMIT ?',
    [id(companyId),capped]);
 }
 return Object.freeze({
  initialize,bootstrapAdmin,login,validateSession,logout,setupRequired,isPlatformAdmin,listUserUnits,
  requireUnitMembership:(userId,unitId)=>member(port,userId,unitId),
  requireCompanyAdmin:(userId,companyId)=>companyAdmin(port,userId,companyId),
  requireCompanyReportingAdmin,createCompany,createUnit,listUnitMembers,
  grantMembership,changeMembership,listAudit
 });
}
